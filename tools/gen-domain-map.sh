#!/bin/sh
# Usage: tools/gen-domain-map.sh [--block | --markers]
# Generates the domain map of ess/, a Mermaid flowchart and a table, into the block between the
# lines `<!-- domain-map -->` and `<!-- /domain-map -->` of website/docs/specification/layers.md
# (or the page DOMAIN_MAP_PAGE names) and leaves the rest of the page as it is. It refuses (exit 2,
# page unchanged) a page whose markers cannot hold the block: see markers() below. --block prints
# the block instead and writes nothing; --markers only checks the markers of the page (exit 1 and
# the reason when they cannot hold it). tools/check.d/30-domain-map.sh holds the committed block
# equal to it. Tests: tools/test-domain-map.sh.
#
# Sources: the domains and their layers from ess/ess-inputs.yaml (the files `<n>-<layer>/*.yaml`
# it lists and the `domain:` line of each), and the references between domains from
# `tools/check-layers.sh --graph` (or the file DOMAIN_MAP_GRAPH names, its saved output).
#
# Drawing: one `subgraph L<n>` per layer, titled with the directory name, layer 9 at the top; one
# node per domain, its id the domain name and its label the name without `weft.`. A pair of
# domains the graph prints is drawn as one edge per pair of layers, `L<n> --> L<m>`, when the two
# domains sit in different layers, and as `<from> --> <to>` between the two domain nodes when they
# share a layer. Layer edges, because one edge per pair of domains (84 on 2026-11-27) renders as a
# tangle nobody can follow; the domains of each layer edge are listed in the table after the
# figure, one row per referring domain with the domains it refers to. Layers are kept in order by
# invisible links (`~~~`) from the first domain of each layer to the first of the layer below.
# Output sorted, so the block changes only when ess/ does.
set -u
LC_ALL=C
export LC_ALL
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root" || exit 2
page=${DOMAIN_MAP_PAGE:-website/docs/specification/layers.md}
inputs=ess/ess-inputs.yaml
[ -f "$inputs" ] || { echo "gen-domain-map: no $inputs" >&2; exit 2; }

if [ -n "${DOMAIN_MAP_GRAPH:-}" ]; then
  graph=$(cat "$DOMAIN_MAP_GRAPH") || exit 2
else
  graph=$(tools/check-layers.sh --graph) || { echo "gen-domain-map: tools/check-layers.sh --graph failed" >&2; exit 2; }
fi

# `<layer> <directory> <domain>` per domain file of ess-inputs.yaml, layer 9 first
layers=$(sed -n 's/^  - \([0-9][0-9]*-[a-z-]*\/[a-z-]*\.yaml\)$/\1/p' "$inputs" | while read -r path; do
  domain=$(sed -n 's/^domain:[ ]*//p' "ess/$path" | head -n 1)
  [ -n "$domain" ] || continue
  dir=${path%%/*}
  printf '%s %s %s\n' "${dir%%-*}" "$dir" "$domain"
done | sort -k1,1nr -k3,3)
[ -n "$layers" ] || { echo "gen-domain-map: no domain file in $inputs" >&2; exit 2; }
# `<from> <to>` per pair of domains, sorted
pairs=$(printf '%s\n' "$graph" | awk 'NF == 0 { exit } NF == 4 && $3 == "->" { print $2, $4 }' | sort -u)

block() {
  echo '<!-- domain-map -->'
  echo '<!-- Generated by tools/gen-domain-map.sh from ess/; do not edit. -->'
  echo
  echo '```mermaid'
  echo 'flowchart TB'
  printf '%s\n' "$layers" | awk '
    $1 != cur { if (cur != "") print "  end"; cur = $1; t = $2; sub(/-/, " ", t); printf "  subgraph L%s[\"%s\"]\n", $1, t }
    { label = $3; sub(/^weft\./, "", label); printf "    %s[\"%s\"]\n", $3, label }
    END { if (cur != "") print "  end" }
  '
  printf '%s\n' "$pairs" | GEN_LAYERS="$layers" awk '
    BEGIN { n = split(ENVIRON["GEN_LAYERS"], row, "\n"); for (i = 1; i <= n; i++) { split(row[i], f, " "); layer[f[3]] = f[1] } }
    NF == 2 {
      a = layer[$1]; b = layer[$2]
      if (a == b) print "  " $1 " --> " $2
      else if (!((a " " b) in seen)) { seen[a " " b] = 1; print "  L" a " --> L" b }
    }
  ' | sort
  printf '%s\n' "$layers" | awk '
    $1 != cur { if (prev != "") print "  " prev " ~~~ " $3; prev = $3; cur = $1 }
  '
  echo '```'
  echo
  echo '| Layer | Domain | Refers to |'
  echo '|---|---|---|'
  printf '%s\n' "$layers" | GEN_PAIRS="$pairs" awk '
    BEGIN {
      n = split(ENVIRON["GEN_PAIRS"], row, "\n")
      for (i = 1; i <= n; i++) {
        if (split(row[i], f, " ") != 2) continue
        t = f[2]; sub(/^weft\./, "", t)
        # test `in` before the element is read: mawk creates it while evaluating the right side
        if (f[1] in to) to[f[1]] = to[f[1]] ", `" t "`"; else to[f[1]] = "`" t "`"
      }
    }
    { d = $3; sub(/^weft\./, "", d); printf "| %s | `%s` | %s |\n", $1, d, ($3 in to ? to[$3] : "none") }
  '
  echo '<!-- /domain-map -->'
}

# markers <page>: prints why the page cannot hold the block, nothing when it can. The page needs
# exactly one `<!-- domain-map -->` line and one `<!-- /domain-map -->` line, the opening one
# first, and neither inside a code fence (``` or ~~~ up to 3 spaces in, closed by a run of the
# same character at least as long), where the site prints the block as text and draws no figure.
markers() {
  awk '
    {
      match($0, /^ */); ind = RLENGTH; s = substr($0, ind + 1)
      if (ind <= 3) {
        if (fch == "") {
          if (match(s, /^(```+|~~~+)/)) { fch = substr(s, 1, 1); fn = RLENGTH; next }
        } else if (substr(s, 1, 1) == fch) {
          if (fch == "`") match(s, /^`+/); else match(s, /^~+/)
          if (RLENGTH >= fn && substr(s, RLENGTH + 1) ~ /^[ \t]*$/) { fch = ""; next }
        }
      }
    }
    $0 == "<!-- domain-map -->" { nopen++; at_open = NR; if (fch != "") fenced_open = 1 }
    $0 == "<!-- /domain-map -->" { nclose++; at_close = NR; if (fch != "") fenced_close = 1 }
    END {
      if (nopen != 1 || nclose != 1) { printf "needs one <!-- domain-map --> and one <!-- /domain-map --> line (found %d and %d)\n", nopen, nclose; exit }
      if (at_close < at_open) { printf "has its <!-- /domain-map --> (line %d) before its <!-- domain-map --> (line %d)\n", at_close, at_open; exit }
      if (fenced_open) printf "has its <!-- domain-map --> (line %d) inside a code fence\n", at_open
      else if (fenced_close) printf "has its <!-- /domain-map --> (line %d) inside a code fence\n", at_close
    }
  ' "$1"
}

case "${1:-}" in
  --block) block; exit $? ;;
  --markers)
    [ -f "$page" ] || { echo "gen-domain-map: no page $page" >&2; exit 2; }
    why=$(markers "$page") || exit 2
    [ -z "$why" ] || { echo "gen-domain-map: $page $why"; exit 1; }
    exit 0 ;;
esac
[ $# -eq 0 ] || { echo "usage: tools/gen-domain-map.sh [--block | --markers]" >&2; exit 2; }
[ -f "$page" ] || { echo "gen-domain-map: no page $page" >&2; exit 2; }
why=$(markers "$page") || exit 2
[ -z "$why" ] || { echo "gen-domain-map: $page $why; the page is left as it is" >&2; exit 2; }
mkdir -p target/domain-map || exit 2
block > target/domain-map/new-block.md || exit 2
awk '
  FILENAME == ARGV[1] { b = b $0 "\n"; next }
  /^<!-- domain-map -->$/ { printf "%s", b; skip = 1; next }
  /^<!-- \/domain-map -->$/ { skip = 0; next }
  !skip { print }
' target/domain-map/new-block.md "$page" > target/domain-map/page.md || exit 2
cat target/domain-map/page.md > "$page"
echo "gen-domain-map: wrote the domain map into $page"
